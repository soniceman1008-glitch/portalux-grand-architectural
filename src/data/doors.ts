export const CURRENCY_RATES: Record<
  CurrencyCode,
  { symbol: string; rate: number; label: string; fullName: string; flag: string }
> = {
  AUD: { symbol: 'A$', rate: 1.0, label: 'AUD', fullName: 'Australian Dollar', flag: '🇦🇺' },
  USD: { symbol: '$', rate: 0.65, label: 'USD', fullName: 'US Dollar', flag: '🇺🇸' },
  EUR: { symbol: '€', rate: 0.60, label: 'EUR', fullName: 'Euro', flag: '🇪🇺' },
  GBP: { symbol: '£', rate: 0.52, label: 'GBP', fullName: 'British Pound', flag: '🇬🇧' },
  PKR: { symbol: '₨ ', rate: 182.0, label: 'PKR', fullName: 'Pakistani Rupee', flag: '🇵🇰' },
  SAR: { symbol: 'SAR ', rate: 2.45, label: 'SAR', fullName: 'Saudi Riyal (ريال)', flag: '🇸🇦' },
};

export function formatPrice(priceInAUD: number, currency: CurrencyCode): string {
  const config = CURRENCY_RATES[currency] || CURRENCY_RATES.AUD;
  const converted = Math.round(priceInAUD * config.rate);
  if (currency === 'PKR') {
    return `₨ ${converted.toLocaleString()} PKR`;
  }
  if (currency === 'SAR') {
    return `${converted.toLocaleString()} SAR`;
  }
  return `${config.symbol}${converted.toLocaleString()} ${config.label}`;
}

